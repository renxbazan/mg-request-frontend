type IconName = keyof typeof ICONS
type ButtonVariant = 'primary' | 'secondary' | 'danger' | 'success' | 'ghost'

export default function IconButton({
  icon,
  title,
  variant = 'secondary',
  onClick,
  to,
  disabled,
  className = '',
  'aria-label': ariaLabel,
  ...rest
}: {
  icon: IconName
  title: string
  variant?: ButtonVariant
  onClick?: () => void
  to?: string
  disabled?: boolean
  className?: string
  'aria-label'?: string
  [key: string]: unknown
}) {
  const variantClass = `btn-${variant}`
  const classes = `btn btn-icon btn-with-tooltip ${variantClass} ${className}`.trim()
  const label = ariaLabel ?? title
  const content = ICONS[icon]

  const commonProps = {
    className: classes,
    ...rest,
    title,
    'aria-label': label,
    'data-tooltip': title,
  }

  if (to && !disabled) {
    return (
      <Link to={to} {...commonProps}>
        {content}
      </Link>
    )
  }

  return (
    <button type="button" disabled={disabled} onClick={onClick} {...commonProps}>
      {content}
    </button>
  )
}
